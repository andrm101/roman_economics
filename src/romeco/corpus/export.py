"""Portable working library: CSL-JSON and BibTeX exports (versioned with the repo).

* ``bib/library.csl.json`` / ``bib/library.bib``  registered sources (source_register.csv), with access status
* ``bib/discovered.csl.json``                     discovery candidates NOT yet registered (state = discovered)

Only fields present in the registers are exported. Nothing is completed from memory; missing
fields stay missing. Each record's ``note`` states its access status so a reader cannot mistake
a cited-only work for an inspected one.
"""

from __future__ import annotations

import json
import re

from romeco.corpus import registry as R

CSL_TYPE = {"work": "book", "edited_volume": "book", "edition": "book", "article": "article-journal",
            "chapter": "chapter", "dataset": "dataset", "web_page": "webpage", "thesis": "thesis",
            "working_paper": "report", "file_copy": "document", "reading": "document"}
BIB_TYPE = {"book": "book", "article-journal": "article", "chapter": "incollection", "dataset": "misc",
            "webpage": "misc", "thesis": "phdthesis", "report": "techreport", "document": "misc"}


def _names(s: str) -> list[dict]:
    out = []
    for n in re.split(r";\s*", s or ""):
        n = n.strip()
        if not n or n.lower().startswith(("et al", "wikipedia")):
            continue
        n = re.sub(r"\s*\((?:eds?|trans|ed\.)\.?\)", "", n)
        parts = n.split()
        if len(parts) < 2:
            out.append({"literal": n})
            continue
        k = next((i for i, w in enumerate(parts[1:], 1) if w.lower() in {"de", "van", "von", "di", "du", "le", "da", "del", "der"}), len(parts) - 1)
        out.append({"family": " ".join(parts[k:]), "given": " ".join(parts[:k])})
    return out


def _ids(s: str) -> dict:
    d = {}
    for tok in re.split(r";\s*", s or ""):
        if tok.startswith("DOI:"):
            d["DOI"] = tok[4:]
        elif tok.startswith("ISBN:"):
            d["ISBN"] = tok[5:]
        elif tok.startswith("URL:"):
            d.setdefault("URL", tok[4:])
    return d


def library() -> list[dict]:
    out = []
    for sid, r in R.sources().items():
        t = CSL_TYPE.get(r["kind"], "document")
        rec = {"id": sid, "type": t, "title": r["title"], "author": _names(r["creators"]),
               "container-title": r.get("container_or_series") or None, "language": r.get("language") or None,
               "note": f"access_status={r['access_status']}; romeco source register", **_ids(r.get("identifiers", ""))}
        if re.fullmatch(r"\d{4}", r.get("year", "") or ""):
            rec["issued"] = {"date-parts": [[int(r["year"])]]}
        out.append({k: v for k, v in rec.items() if v not in (None, "", [])})
    return out


def discovered() -> list[dict]:
    out = []
    for r in R.read("discovery_candidates.csv"):
        if r["state"] != "discovered":
            continue
        rec = {"id": r["cand_id"], "type": "document", "title": r["title"] or None,
               "author": [{"literal": r["authors"]}] if r["authors"] else [],
               "note": f"state=discovered (not acquired, not read); cited in {r['cited_in']}; parsed by romeco.corpus.discover"}
        y = re.match(r"\d{4}", r["year"] or "")
        if y:
            rec["issued"] = {"date-parts": [[int(y.group())]]}
        out.append({k: v for k, v in rec.items() if v not in (None, "", [])})
    return out


def to_bibtex(recs: list[dict]) -> str:
    lines = []
    for r in recs:
        key = re.sub(r"[^A-Za-z0-9]", "", r["id"])
        f = {"title": r.get("title"), "year": (r.get("issued") or {}).get("date-parts", [[None]])[0][0],
             "author": " and ".join(a.get("literal") or f"{a['family']}, {a['given']}" for a in r.get("author", [])) or None,
             "journal" if r["type"] == "article-journal" else "booktitle" if r["type"] == "chapter" else "howpublished": r.get("container-title"),
             "doi": r.get("DOI"), "isbn": r.get("ISBN"), "url": r.get("URL"), "note": r.get("note")}
        body = ",\n".join(f"  {k} = {{{v}}}" for k, v in f.items() if v)
        lines.append(f"@{BIB_TYPE.get(r['type'], 'misc')}{{{key},\n{body}\n}}\n")
    return "\n".join(lines)


def export() -> dict:
    lib, dis = library(), discovered()
    b = R.ROOT / "bib"
    (b / "library.csl.json").write_text(json.dumps(lib, ensure_ascii=False, indent=1), encoding="utf-8")
    (b / "library.bib").write_text("% Generated by romeco.corpus.export from registers/source_register.csv. Do not edit by hand.\n\n"
                                   + to_bibtex(lib), encoding="utf-8")
    (b / "discovered.csl.json").write_text(json.dumps(dis, ensure_ascii=False, indent=1), encoding="utf-8")
    return dict(library=len(lib), discovered=len(dis))
