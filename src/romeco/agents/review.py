"""WP11 review packets: what a human needs to accept or reject one extraction candidate.

A packet is written to review_queue/<ext_id>/ (git-ignored: it may contain page images of
all-rights-reserved works). The human's decision goes to registers/review_decisions.csv,
which subagents cannot write (policy human_only_paths).
"""

from __future__ import annotations

import csv
import shutil
import subprocess
from pathlib import Path

from romeco.agents.policy import ROOT

QUEUE = ROOT / "review_queue"


def _rows(p: Path) -> list[dict]:
    return list(csv.DictReader(open(p, encoding="utf-8")))


def candidate(ext_id: str) -> dict:
    for r in _rows(ROOT / "data" / "derived" / "corpus" / "extractions.csv"):
        if r["ext_id"] == ext_id:
            return r
    raise KeyError(ext_id)


def make_packet(ext_id: str, render: bool = True, out_root: Path = QUEUE) -> Path:
    c = candidate(ext_id)
    items = {i["item_id"]: i for i in _rows(ROOT / "registers" / "corpus" / "items.csv")}
    it = items[c["item_id"]]
    out = out_root / ext_id
    out.mkdir(parents=True, exist_ok=True)
    image = None
    raw = ROOT / it["cache_path"] if it.get("cache_path") else None
    if render and raw and raw.exists() and it["media_type"] == "application/pdf" and c["pdf_page"] and shutil.which("pdftoppm"):
        pg = c["pdf_page"]
        subprocess.run(["pdftoppm", "-f", pg, "-l", pg, "-r", "110", "-png", "-singlefile", str(raw), str(out / "page")],
                       check=True, capture_output=True)
        image = out / "page.png"
    fields = ["ext_id", "source_id", "unit_ref", "pdf_page", "printed_page", "locus", "kind", "rule", "raw",
              "value_low", "value_high", "unit", "norm_key", "conf", "extractor_version", "snippet"]
    lines = [f"# Review packet {ext_id}", "",
             "Candidate only (D024). Decide in `registers/review_decisions.csv`; do not edit this file.", "",
             "| field | value |", "|---|---|"]
    lines += [f"| {k} | {str(c.get(k, '')).replace('|', '/')} |" for k in fields]
    lines += ["", f"Page image: `{image.relative_to(ROOT) if image.is_relative_to(ROOT) else image.name}`" if image else "Page image: not rendered (no local PDF page)",
              "", "## Checklist for the reviewer",
              "- [ ] The value/citation is on the page as extracted (check the image, not the text layer).",
              "- [ ] Units and numerals read correctly (ligatures, overlines, OCR digits).",
              "- [ ] It is the author's own claim, or a report of another source (record which).",
              "- [ ] Which ancient document / locus it bears on.",
              "", "## Decision row template", "",
              "```", "decision_id,ext_id,decision,reviewer,date,claim_id,corrections,note",
              f"RVD-NNNN,{ext_id},accept|accept_corrected|reject|defer,andrei,YYYY-MM-DD,<new assertion_id>,,", "```"]
    (out / "packet.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
